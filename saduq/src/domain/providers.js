/** รีวิวของเจ้านั้น (จำลอง) — คงที่ทุกครั้ง */
export function reviewsOf(p, n = 6) {
  const r = rng(p.id + 'rv'), pool = TEXTS[p.kind] || TEXTS.care;
  return Array.from({ length: Math.min(n, p.reviews) }, () => {
    const low = r() > p.rating - 3.6; // คะแนนเฉลี่ยต่ำ → มีรีวิว 4 ดาวมากขึ้น
    const f = FOR[Math.floor(r() * FOR.length)];
    return { name: NAMES[Math.floor(r() * NAMES.length)], who: WHO[Math.floor(r() * WHO.length)] + 'ของผู้รับบริการ',
      stars: low ? 4 : 5, text: pool[Math.floor(r() * pool.length)].replace('{f}', f), ago: AGO[Math.floor(r() * AGO.length)] };
  });
}
/** สัดส่วนดาว 5..1 จากคะแนนเฉลี่ย */
export function breakdown(p) {
  const five = Math.max(0, Math.min(1, (p.rating - 4) * 0.95)), four = Math.max(0, 1 - five - 0.06);
  return [five, four, 0.04, 0.015, 0.005].map(x => Math.round(x * p.reviews));
}
